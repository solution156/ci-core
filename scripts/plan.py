#!/usr/bin/env python3
"""Generate isolated per-image DAGs. JSON is a YAML 1.2 subset; no PyYAML at runtime."""
from __future__ import annotations
import argparse
import json
import pathlib
import re
from catalog import env, fail, plan, require, write


def generate(output):
    selection = plan()
    write('pipeline-plan.json', selection)
    project, revision = require('CI_CORE_PROJECT'), require('CI_CORE_REF')
    for key, value in (('CI_CORE_PROJECT', project), ('CI_CORE_REF', revision)):
        if not re.fullmatch(r'[a-zA-Z0-9._/-]+', value) or '..' in value:
            fail(key + ' không hợp lệ')
    if not selection['images']:
        config = {'stages': ['report'], 'images:no-changes': {
            'stage': 'report', 'image': env('PYTHON_IMAGE', 'rd-harbor-secops.servicemicro.net/build/ci-tools:v1'),
            'script': ['echo "No affected images; validation completed."']}}
    else:
        config = {
            'include': [{'project': project, 'ref': revision, 'file': '/templates/workspace-child.yaml'}],
            'variables': {'CI_CORE_PROJECT': project, 'CI_CORE_REF': revision,
                          'ROOT_PIPELINE_ID': selection['pipeline_id'],
                          'WORKSPACE_REF_KIND': selection['ref_kind'],
                          'PARENT_PIPELINE_SOURCE': selection['source'],
                          'PARENT_COMMIT_BRANCH': env('CI_COMMIT_BRANCH'),
                          'PARENT_COMMIT_TAG': env('CI_COMMIT_TAG'),
                          'PARENT_REF_PROTECTED': env('CI_COMMIT_REF_PROTECTED')},
        }
        def job(prefix, template, row, needs, **extra):
            name = prefix + ':' + row['id']
            config[name] = {
                'extends': template,
                'variables': {'IMAGE_ID': row['id'], 'IMAGE_VERSION': row['version'],
                              'IMAGE_REPOSITORY': row['repository'],
                              'IMAGE_CANDIDATE_TAG': row['candidate_tag'], 'IMAGE_FINAL_TAG': row['final_tag']},
                'needs': [{'job': n, 'artifacts': True} for n in needs], **extra}
            return name
        for row in selection['images']:
            name = row['id']
            if selection['mode'] == 'bootstrap':
                lock = job('lock', '.workspace-lock', row, ['ci:tools'])
                job('cleanup', '.workspace-cleanup', row, [lock], when='always')
                continue
            if selection['mode'] == 'fast':
                smoke = job('build', '.workspace-smoke', row, ['ci:tools'])
                job('cleanup', '.workspace-cleanup', row, [smoke], when='always')
                continue
            build = job('build', '.workspace-build', row, ['ci:tools'])
            scan = job('scan', '.workspace-scan', row, [build])
            patch = job('patch', '.workspace-patch', row, ['ci:tools', build, scan])
            verify = job('verify:trivy', '.workspace-verify-trivy', row, [patch])
            runtime = job('verify:runtime', '.workspace-verify-runtime', row, ['ci:tools', patch])
            sbom = job('gen-sbom', '.workspace-sbom', row, [patch, verify, runtime])
            evidence = job('evidence', '.workspace-evidence', row, ['ci:tools', build, scan, patch, verify, runtime, sbom])
            sign = job('sign', '.workspace-sign', row, [evidence])
            promote_needs = ['ci:tools', sign]
            if env('DEVGUARD_ENABLED', 'false').lower() == 'true':
                promote_needs.append(job('devguard', '.workspace-devguard', row, [sign]))
            promote = job('promote', '.workspace-promote', row, promote_needs,
                          resource_group='workspace-promote-' + name)
            last = promote
            if selection['mode'] == 'release':
                last = job('release', '.workspace-release', row, ['ci:tools', promote])
            job('cleanup', '.workspace-cleanup', row, [last], when='always')
    pathlib.Path(output).write_text('# Generated by ci-core; do not edit.\n' + json.dumps(config, indent=2) + '\n', encoding='utf-8')
    print('Child pipeline:', selection['mode'], selection['reason'], ', '.join(r['id'] for r in selection['images']) or '(no changes)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default='generated-child.yml')
    args = parser.parse_args()
    try:
        generate(args.output)
    except (OSError, ValueError, KeyError) as exc:
        fail(f'Không tạo được plan: {exc}')


if __name__ == '__main__':
    main()
